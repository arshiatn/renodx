// A jump out of a stub back into the game: where its rel32 is in the stub's bytes, and where it goes.
struct StubExit {
  uint16_t rel32_offset = 0;
  uint32_t target = 0;
};
inline constexpr std::array<StubExit, 2> SPRITE_ROWS_EXITS = {{
    {.rel32_offset = 0x4b9, .target = SPRITE_ROWS_DONE},
    {.rel32_offset = 0x4c4, .target = SPRITE_ROWS_FALLBACK},
}};
// Each exit's rel32 follows a jmp rel32 opcode.
static_assert(std::ranges::all_of(SPRITE_ROWS_EXITS, [](const StubExit& stub_exit) {
  return SPRITE_ROWS[stub_exit.rel32_offset - 1] == 0xe9;
}));

// A site's stub: its bytes and its jumps back into the game. No bytes: none is placed, the site is only checked.
struct Stub {
  const char* word = nullptr;  // in the log's stub line
  std::span<const uint8_t> code;
  std::span<const StubExit> exits;
};
inline constexpr std::array<Stub, LABEL_COUNT> STUBS = [] {
  std::array<Stub, LABEL_COUNT> stubs = {};
  stubs[LABEL_SPRITE_ROWS] = {.word = "sprite rows", .code = SPRITE_ROWS, .exits = SPRITE_ROWS_EXITS};
  return stubs;
}();

// Where each placed stub's block lies in the row's code, and that code's size.
struct Layout {
  std::array<uint16_t, LABEL_COUNT> offsets = {};
  uint16_t bytes = 0;
};
inline constexpr size_t BLOCK_ALIGNMENT = 64;
inline constexpr Layout LAYOUT = [] {
  Layout layout;
  for (const Site& site : SITES) {
    const Stub& stub = STUBS[site.label];
    if (stub.code.empty()) continue;
    layout.offsets[site.label] = layout.bytes;
    layout.bytes += static_cast<uint16_t>((stub.code.size() + BLOCK_ALIGNMENT - 1) & ~(BLOCK_ALIGNMENT - 1));
  }
  return layout;
}();
// The row's code as it is placed, but for the stubs' jumps back into the game: every placed stub's bytes at its
// offset, int3 between the blocks.
inline constexpr std::array<uint8_t, LAYOUT.bytes> CODE = [] {
  std::array<uint8_t, LAYOUT.bytes> code = {};
  code.fill(0xcc);
  for (const Site& site : SITES) {
    std::ranges::copy(STUBS[site.label].code, code.begin() + LAYOUT.offsets[site.label]);
  }
  return code;
}();

// Blocks start on a cache line of their own. In front of the first one a gap keeps the stubs out of the 1 KiB
// subpage of data the loader writes into its page while the game runs (Intel 64 and IA-32 Architectures Optimization
// Reference Manual, "Mixing Code and Data": no writes into the 1 KiB subpage of code that runs). Ours: the manual's
// 2 KiB rule for fetched code is not kept, the loader's 8 KiB page has no room for it; a speed matter only.
inline constexpr size_t LEAD_GAP_BYTES = 0x400;

