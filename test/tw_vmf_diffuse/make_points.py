# Writes s0_points.h, S0's reference points the CPU twin is checked against (independent of vmf_diffuse.h's copy):
# - T0's points (vmf_s0.exe t0, designs/vmf_s0/t0_points.csv): the walk (4e6 paths an incident angle, noise <= 0.06 %)
#   and S0's double-precision corrected model, for T0's r grid {0.005, 0.05, 0.15, 0.26, 0.40} (Eqs. 4 / 5 / 5 / 5 / 6),
#   c {0.1, 0.5, 0.8} and T0's main set (u_i, u_o >= 0.2);
# - beta's check points (vmf_s0.exe beta, designs/vmf_s0/beta_check.csv): S0's interpolated beta at 10 r x 8 base off
#   the table's nodes.
# usage: python -I make_points.py <t0_points.csv> <beta_check.csv> <s0_points.h>
import csv
import sys

R = {0.005, 0.05, 0.15, 0.26, 0.4}
C = {0.1, 0.5, 0.8}
rows = []
with open(sys.argv[1], newline='') as f:
    for row in csv.DictReader(f):
        r, c = float(row['r']), float(row['c'])
        theta_in, theta_out = float(row['theta_in']), float(row['theta_out'])
        if r in R and c in C and theta_in <= 78.46 and theta_out <= 78.46:
            rows.append((row['r'], row['c'], row['theta_in'], row['theta_out'], row['phi_out'], row['walk'],
                         row['model']))
with open(sys.argv[2], newline='') as f:
    betas = [(row['r'], row['base'], row['beta']) for row in csv.DictReader(f)]
with open(sys.argv[3], 'w', newline='\n') as f:
    f.write('// Generated by make_points.py from designs/vmf_s0/t0_points.csv and beta_check.csv\n'
            '// (S0, vmf_s0.exe t0 / beta).\n')
    f.write('#ifndef TEST_TW_VMF_DIFFUSE_S0_POINTS_H_\n#define TEST_TW_VMF_DIFFUSE_S0_POINTS_H_\n\n')
    f.write('// r, c, incident and outgoing angles (degrees; phi 0 = backscatter), the walk\'s f and S0\'s corrected\n'
            '// model\'s f (double).\n')
    f.write('struct T0Point {\n  double r;\n  double c;\n  double theta_in;\n  double theta_out;\n  double phi_out;\n'
            '  double walk;\n  double model;\n};\n\n')
    f.write(f'static const T0Point T0_POINTS[{len(rows)}] = {{\n')
    for row in rows:
        f.write('    {' + ', '.join(row) + '},\n')
    f.write('};\n\n')
    f.write('// r, base and S0\'s beta there (6 digits).\n')
    f.write('struct BetaPoint {\n  double r;\n  double base;\n  double beta;\n};\n\n')
    f.write(f'static const BetaPoint BETA_POINTS[{len(betas)}] = {{\n')
    for row in betas:
        f.write('    {' + ', '.join(row) + '},\n')
    f.write('};\n\n#endif  // TEST_TW_VMF_DIFFUSE_S0_POINTS_H_\n')
print(len(rows), 'T0 points,', len(betas), 'beta points')
